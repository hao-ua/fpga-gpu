#!/usr/bin/env python3
"""gen_exports — libGLESv2.def, libEGL.def, gles_stubs_gen.c with ANGLE's export ordinals, and gles_entry_gen.h, the exports themselves. Games linked against ANGLE
(Contraption Maker) import by ordinal, so a function at another number would be a different function.
An export is a wrapper, w_<name>: it takes the library's lock, puts the calling thread's context in place for a GL function, calls the implementation and lets the lock go
(gles_main.c includes gles_entry_gen.h at its end). The .def exports <name> = w_<name>; calls inside the library go to the implementations directly.

    python3 host/win/gles/gen_exports.py angle_gles.txt angle_egl.txt        (run from the repository root)
        the export tables of an ANGLE build, as text (`objdump -p libGLESv2.dll > angle_gles.txt`, the same for libEGL). Exports nothing here implements become stubs that log their name.
    python3 host/win/gles/gen_exports.py
        libGLESv2.def again from itself, its ordinals kept, and gles_entry_gen.h: after a function was added to or removed from gles_main.c (a new export needs its line in the .def first)
"""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))


def exports(path):
    """[(ordinal, name)]: objdump lists '[   0] name' from zero, ordinal = index + base"""
    t = open(path, encoding='latin-1').read()
    base = int(re.search(r'Ordinal Base\s+(\d+)', t).group(1))
    out = []
    part = t[t.index('[Ordinal/Name Pointer] Table') if '[Ordinal/Name Pointer] Table' in t else t.index('Ordinal/Name Pointer'):]
    for m in re.finditer(r'^\s*\[\s*(\d+)\]\s+(\S+)\s*$', part, re.M):
        out.append((int(m.group(1)) + base, m.group(2)))
    return out


def def_exports(path):
    """[(ordinal, name)] of a .def this script wrote"""
    out = []
    for line in open(path, encoding='utf-8'):
        m = re.match(r'^\s+(\w+)(?:\s*=\s*\S+)?\s+@(\d+)\s*$', line)
        if m: out.append((int(m.group(2)), m.group(1)))
    return out


src = open(os.path.join(HERE, 'gles_main.c'), encoding='utf-8').read()
# name -> (return type, calling convention, parameter list): every definition 'type ES_APIENTRY glX(params)' / 'type EGLAPI eglX(params)', and the UF / UI uniform setters
funcs = {}
for m in re.finditer(r'^((?:const\s+)?\w+\s*\**)\s*(ES_APIENTRY|EGLAPI)\s+((?:gl|egl)\w+)\s*\(([^)]*)\)', src, re.M):
    funcs.setdefault(m.group(3), (m.group(1).strip(), m.group(2), ' '.join(m.group(4).split())))
for m in re.finditer(r'^U[FI]\((gl\w+)\(([^)]*)\)', src, re.M):
    funcs.setdefault(m.group(1), ('void', 'ES_APIENTRY', ' '.join(m.group(2).split())))
defined = set(funcs)

if len(sys.argv) == 3:
    gles = exports(sys.argv[1])
    egl = exports(sys.argv[2])
    extra = sorted(n for n in defined if n.startswith('gl') and n not in {x[1] for x in gles})
    missing = [n for o, n in gles if n not in defined]
    top = max(o for o, _ in gles)
    table = list(gles)
    for n in extra: top += 1; table.append((top, n))
    for n in sorted(x for x in defined if x.startswith('egl')): top += 1; table.append((top, n))
    with open(os.path.join(HERE, 'libEGL.def'), 'w', newline='\n') as f:
        f.write('LIBRARY libEGL.dll\nEXPORTS\n')
        for o, n in egl:
            f.write('    %s = libGLESv2.%s @%d\n' % (n, n if n in defined else 'eglGetError', o))
    with open(os.path.join(HERE, 'gles_stubs_gen.c'), 'w', newline='\n') as f:
        f.write('/* generated by gen_exports.py: exports of an ANGLE build that this library does not implement (its own extensions). A call logs the name once and does nothing. */\n#include "g2_env.h"\n')
        for n in missing:
            f.write('void __stdcall %s(void) { static int s; if (!s++) g2e_log("gles: %s is not implemented"); }\n' % (n, n))
    print('%d GLES exports, %d stubs: %s' % (len(gles), len(missing), ' '.join(missing)))
    print('%d EGL exports, not here: %s' % (len(egl), ' '.join(n for o, n in egl if n not in defined)))
    print('beyond ANGLE: %s' % ' '.join(extra))
elif len(sys.argv) == 1:
    table = def_exports(os.path.join(HERE, 'libGLESv2.def'))
else:
    sys.exit(__doc__)

with open(os.path.join(HERE, 'libGLESv2.def'), 'w', newline='\n') as f:
    f.write('LIBRARY libGLESv2.dll\nEXPORTS\n')
    for o, n in table: f.write(('    %s = w_%s @%d\n' % (n, n, o)) if n in defined else ('    %s @%d\n' % (n, o)))


def arg_names(params):
    if params in ('', 'void'): return []
    return [re.search(r'(\w+)\s*(?:\[[^\]]*\])?\s*$', p.strip()).group(1) for p in params.split(',')]


wrapped = [n for o, n in table if n in defined]
with open(os.path.join(HERE, 'gles_entry_gen.h'), 'w', newline='\n') as f:
    f.write('/* generated by gen_exports.py, included once at the end of gles_main.c: the exports. Each takes the library\'s lock around the implementation; a GL function first puts\n'
            '   its thread\'s context and surface in place (gl_enter) */\n')
    for n in wrapped:
        ret, cc, params = funcs[n]
        enter = 'gl_enter' if n.startswith('gl') else 'egl_enter'
        args = ', '.join(arg_names(params))
        sep = '' if ret.endswith('*') else ' '
        if ret == 'void':
            body = '%s(); %s(%s); api_leave();' % (enter, n, args)
        else:
            body = '%s%sr_; %s(); r_ = %s(%s); api_leave(); return r_;' % (ret, sep, enter, n, args)
        f.write('%s%s%s w_%s(%s) { %s }\n' % (ret, sep, cc, n, params if params else 'void', body))
print('%d exports wrapped; defined here but not exported: %s' % (len(wrapped), ' '.join(sorted(defined - set(wrapped))) or 'none'))
