#!/usr/bin/env python3
"""gen_exports — opengl32.def and gl_stubs_gen.c from the GL 1.1 entry points of gl.h. A game that links a missing export does not even load, so every one of the 336 is exported;
whatever no gl_*.c file defines becomes a stub that records GL_INVALID_OPERATION and logs its name, so the list of what is unimplemented is exact (`gl_stubs_gen.c`).

    python3 host/win/gl/gen_exports.py <path to GL/gl.h>      (run from the repository root; rerun when an entry point gets implemented)
"""
import glob, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
gl_h = open(sys.argv[1], encoding='latin-1').read()
protos = {}
for m in re.finditer(r'WINGDIAPI\s+([\w\s\*]+?)\s*APIENTRY\s+(gl\w+)\s*\(([^;]*?)\)\s*;', gl_h):
    protos[m.group(2)] = (' '.join(m.group(1).split()), ' '.join(m.group(3).split()))
src = ''
for f in glob.glob(os.path.join(HERE, 'gl_*.c')):
    if os.path.basename(f) != 'gl_stubs_gen.c':
        src += open(f, encoding='utf-8').read()
defined = set(re.findall(r'APIENTRY\s+(gl\w+)\s*\(', src))
for m in re.finditer(r'^(V_FUNCS|COL_FUNCS|NRM_FUNCS|RECT_FUNCS|RP_FUNCS)\((\w+),', src, re.M):
    kind, sfx = m.group(1), m.group(2)
    if kind == 'V_FUNCS':
        for n in '234': defined.update(('glVertex%s%s' % (n, sfx), 'glVertex%s%sv' % (n, sfx)))
        for n in '1234': defined.update(('glTexCoord%s%s' % (n, sfx), 'glTexCoord%s%sv' % (n, sfx)))
    elif kind == 'COL_FUNCS':
        for n in '34': defined.update(('glColor%s%s' % (n, sfx), 'glColor%s%sv' % (n, sfx)))
    elif kind == 'NRM_FUNCS': defined.update(('glNormal3%s' % sfx, 'glNormal3%sv' % sfx))
    elif kind == 'RECT_FUNCS': defined.update(('glRect%s' % sfx, 'glRect%sv' % sfx))
    else:
        for n in '234': defined.update(('glRasterPos%s%s' % (n, sfx), 'glRasterPos%s%sv' % (n, sfx)))
for m in re.finditer(r'^MAP_FUNCS\((\w+),', src, re.M): defined.update(('glMap1%s' % m.group(1), 'glMap2%s' % m.group(1)))
for m in re.finditer(r'^GETMAP\((\w+),', src, re.M): defined.add('glGetMap%sv' % m.group(1))
missing = sorted(n for n in protos if n not in defined)
out = ['/* generated by gen_exports.py: the GL 1.1 entry points nothing implements. Each records GL_INVALID_OPERATION and logs its name once. */', '#include "gl_internal.h"',
       'static void unimpl(const char *n, int *seen) { if (!*seen) { *seen = 1; g2e_log("gl: %s is not implemented", n); } SET_ERROR(GL_INVALID_OPERATION); }']
for n in missing:
    ret, args = protos[n]
    names = re.findall(r'(\w+)\s*(?:,|$)', args) if args != 'void' else []
    body = 'static int s; unimpl("%s", &s);' % n
    if args != 'void':
        body = ' '.join('(void)%s;' % a for a in names) + ' ' + body
    if ret != 'void': body += ' return 0;'
    out.append('%s APIENTRY %s(%s) { %s }' % (ret, n, args, body))
open(os.path.join(HERE, 'gl_stubs_gen.c'), 'w', newline='\n').write('\n'.join(out) + '\n')
wgl = """wglChoosePixelFormat wglCopyContext wglCreateContext wglCreateLayerContext wglDeleteContext wglDescribeLayerPlane wglDescribePixelFormat wglGetCurrentContext wglGetCurrentDC
wglGetDefaultProcAddress wglGetLayerPaletteEntries wglGetPixelFormat wglGetProcAddress wglMakeCurrent wglRealizeLayerPalette wglSetLayerPaletteEntries wglSetPixelFormat wglShareLists
wglSwapBuffers wglSwapLayerBuffers wglSwapMultipleBuffers wglUseFontBitmapsA wglUseFontBitmapsW wglUseFontOutlinesA wglUseFontOutlinesW""".split()
with open(os.path.join(HERE, 'opengl32.def'), 'w', newline='\n') as f:
    f.write('LIBRARY opengl32.dll\nEXPORTS\n')
    for n in sorted(protos) + wgl: f.write('    %s\n' % n)
print('%d GL 1.1 entry points, %d implemented, %d stubs:' % (len(protos), len(protos) - len(missing), len(missing)))
print(' '.join(missing))
