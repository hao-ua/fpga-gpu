#!/usr/bin/env python3
"""gen_exports — libGLESv2.def, libEGL.def, gles_stubs_gen.c with ANGLE's export ordinals. Games linked against ANGLE (Contraption Maker) import by ordinal, so a function at another number would be a different function.
Input: the export tables of an ANGLE build, as text (`objdump -p libGLESv2.dll > angle_gles.txt`, the same for libEGL). Exports nothing here implements become stubs that log their name.

    python3 host/win/gles/gen_exports.py angle_gles.txt angle_egl.txt        (run from the repository root)
"""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))


def exports(path):
    """[(ordinal, name)]: objdump lists '[   0] name' from zero, ordinal = index + base"""
    t = open(path, encoding='latin-1').read()
    base = int(re.search(r'Ordinal Base\s+(\d+)', t).group(1))
    out = []
    part = t[t.index('[Ordinal/Name Pointer] Table') if '[Ordinal/Name Pointer] Table' in t else t.index('Ordinal/Name Pointer'):]
    for m in re.finditer(r'^\s*\[\s*(\d+)\]\s+(\S+)\s*$', part, re.M):
        out.append((int(m.group(1)) + base, m.group(2)))
    return out


src = open(os.path.join(HERE, 'gles_main.c'), encoding='utf-8').read()
defined = set(re.findall(r'ES_APIENTRY\s+(gl\w+)\s*\(', src)) | set(re.findall(r'^U[FI]\((gl\w+)\(', src, re.M)) | set(re.findall(r'EGLAPI\s+(egl\w+)\s*\(', src))
gles = exports(sys.argv[1])
egl = exports(sys.argv[2])
extra = sorted(n for n in defined if n.startswith('gl') and n not in {x[1] for x in gles})
missing = [n for o, n in gles if n not in defined]
with open(os.path.join(HERE, 'libGLESv2.def'), 'w', newline='\n') as f:
    f.write('LIBRARY libGLESv2.dll\nEXPORTS\n')
    for o, n in gles: f.write('    %s @%d\n' % (n, o))
    top = max(o for o, _ in gles)
    for n in extra: top += 1; f.write('    %s @%d\n' % (n, top))
    for n in sorted(x for x in defined if x.startswith('egl')): top += 1; f.write('    %s @%d\n' % (n, top))
with open(os.path.join(HERE, 'libEGL.def'), 'w', newline='\n') as f:
    f.write('LIBRARY libEGL.dll\nEXPORTS\n')
    for o, n in egl:
        f.write('    %s = libGLESv2.%s @%d\n' % (n, n if n in defined else 'eglGetError', o))
with open(os.path.join(HERE, 'gles_stubs_gen.c'), 'w', newline='\n') as f:
    f.write('/* generated by gen_exports.py: exports of an ANGLE build that this library does not implement (its own extensions). A call logs the name once and does nothing. */\n#include "g2_env.h"\n')
    for n in missing:
        f.write('void __stdcall %s(void) { static int s; if (!s++) g2e_log("gles: %s is not implemented"); }\n' % (n, n))
print('%d GLES exports, %d stubs: %s' % (len(gles), len(missing), ' '.join(missing)))
print('%d EGL exports, not here: %s' % (len(egl), ' '.join(n for o, n in egl if n not in defined)))
print('beyond ANGLE: %s' % ' '.join(extra))
