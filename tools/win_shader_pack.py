#!/usr/bin/env python3
"""win_shader_pack — GLSL ES programs compiled offline by tools/glslc.py + tools/isa64.py into a C table built into the
Windows libraries (no Python on the gaming path).

  python3 tools/win_shader_pack.py OUT.h NAME=STAGE:FILE [NAME=STAGE:FILE ...]        STAGE = vs | fs

The output defines, per program NAME: the 64-bit instruction words, the compiler's constants (hex floats: exact) and
const_base. Run from WSL (Windows has no Python here); the generated header is committed.
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import glslc, isa64


def emit(name, stage, path):
    r = glslc.compile_stage(open(path).read(), stage, isa64=True)
    words, _ = isa64.assemble(r['sasm'].splitlines(), vs=stage == 'vs')
    out = [f"/* {os.path.basename(path)}: {len(words)} instructions, const_base {r['const_base']} */"]
    out.append(f"static const uint64_t {name}_words[{len(words)}] = {{")
    for i in range(0, len(words), 4):
        out.append("    " + ", ".join("0x%016xull" % (w & 0xFFFFFFFFFFFFFFFF) for w in words[i:i + 4]) + ",")
    out.append("};")
    pool = [tuple(float(c) for c in k) for k in r['const_pool']]
    if pool:
        out.append(f"static const double {name}_const[{len(pool)}][4] = {{")
        for v in pool:
            out.append("    { " + ", ".join(c.hex() for c in v) + " },")
        out.append("};")
    else:
        out.append(f"static const double {name}_const[1][4] = {{ {{ 0, 0, 0, 0 }} }};")
    out.append(f"enum {{ {name}_nwords = {len(words)}, {name}_const_base = {r['const_base']}, {name}_nconst = {len(pool)} }};")
    return "\n".join(out)


def main():
    if len(sys.argv) < 3:
        raise SystemExit(__doc__)
    parts = ["/* generated by tools/win_shader_pack.py: do not edit */", "#include <stddef.h>", "#include <stdint.h>"]
    for spec in sys.argv[2:]:
        name, rest = spec.split('=', 1)
        stage, path = rest.split(':', 1)
        parts.append(emit(name, stage, path))
    with open(sys.argv[1], 'w') as f:
        f.write("\n".join(parts) + "\n")
    print(f"wrote {sys.argv[1]}: {len(sys.argv) - 2} programs")


if __name__ == '__main__':
    main()
